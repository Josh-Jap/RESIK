-- ===================================================
-- Database Schema for RESIK (Waste Management System)
-- Compatible with PostgreSQL & Supabase
-- ===================================================

-- 1. Create Housing Table
CREATE TABLE IF NOT EXISTS "Housing" (
    id_house BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_house TEXT NOT NULL,
    address VARCHAR(255),
    house_code BIGINT,
    house_num BIGINT,
    block VARCHAR(50)
);

-- 2. Create User Table
CREATE TABLE IF NOT EXISTS "User" (
    id_users BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_users VARCHAR(255) NOT NULL,
    phone_num NUMERIC,
    email VARCHAR(255) UNIQUE,
    role VARCHAR(50), -- e.g. 'admin', 'petugas', 'warga'
    password VARCHAR(255),
    id_house BIGINT,
    CONSTRAINT fk_user_housing
        FOREIGN KEY (id_house) 
        REFERENCES "Housing"(id_house) 
        ON DELETE SET NULL 
        ON UPDATE CASCADE
);

-- 3. Create Payments Table
CREATE TABLE IF NOT EXISTS "Payments" (
    id_payments BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_users BIGINT NOT NULL,
    qris_reference VARCHAR(255),
    paid_at TIMESTAMP,
    month TEXT,
    year INT,
    amount BIGINT,
    CONSTRAINT fk_payments_user
        FOREIGN KEY (id_users) 
        REFERENCES "User"(id_users) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
);

-- 4. Create Pickup_req Table
CREATE TABLE IF NOT EXISTS "Pickup_req" (
    id_pickup BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    id_users BIGINT NOT NULL,
    pickup_date TIMESTAMPTZ,
    status TEXT DEFAULT 'pending', -- e.g. 'pending', 'in_progress', 'completed', 'cancelled'
    category TEXT,
    photo VARCHAR(500),
    CONSTRAINT fk_pickup_user
        FOREIGN KEY (id_users) 
        REFERENCES "User"(id_users) 
        ON DELETE CASCADE 
        ON UPDATE CASCADE
    -- Optional: If you want to link pickup requests to a user:
    -- id_users BIGINT REFERENCES "User"(id_users) ON DELETE CASCADE
);

-- ===================================================
-- Recommended Indexes for Performance
-- ===================================================
CREATE INDEX IF NOT EXISTS idx_user_id_house ON "User"(id_house);
CREATE INDEX IF NOT EXISTS idx_payments_id_users ON "Payments"(id_users);
CREATE INDEX IF NOT EXISTS idx_pickup_req_status ON "Pickup_req"(status);

-- ===================================================
-- Row Level Security (RLS) - Tahap Development
-- ===================================================
-- Catatan: Supabase secara default mengaktifkan RLS.
-- Jika saat testing di Flutter data tidak muncul / ditolak,
-- Anda bisa matikan RLS untuk testing atau buat policy izinkan akses:

ALTER TABLE "Housing" DISABLE ROW LEVEL SECURITY;
ALTER TABLE "User" DISABLE ROW LEVEL SECURITY;
ALTER TABLE "Payments" DISABLE ROW LEVEL SECURITY;
ALTER TABLE "Pickup_req" DISABLE ROW LEVEL SECURITY;

