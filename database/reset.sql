-- 4. Buat Tabel Schedule & Waste_log jika belum ada
CREATE TABLE IF NOT EXISTS "Schedule" (
    id_schedule BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time VARCHAR(100) NOT NULL,
    area VARCHAR(255) NOT NULL,
    type VARCHAR(100) NOT NULL,
    status VARCHAR(50) DEFAULT 'Baru',
    date VARCHAR(100),
    day VARCHAR(50),
    officer VARCHAR(255),
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS "Waste_log" (
    id_log BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area VARCHAR(255) NOT NULL,
    organik_kg NUMERIC(10,2) DEFAULT 0,
    non_organik_kg NUMERIC(10,2) DEFAULT 0,
    total_kg NUMERIC(10,2) DEFAULT 0,
    officer_name VARCHAR(255),
    id_schedule BIGINT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

